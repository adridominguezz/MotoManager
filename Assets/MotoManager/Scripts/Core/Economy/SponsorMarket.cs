using System;
using System.Collections.Generic;
using MotoManager.Core.Career;
using MotoManager.Core.Common;
using MotoManager.Core.Data;
using MotoManager.Core.World;

namespace MotoManager.Core.Economy
{
    public class SponsorActionResult
    {
        public bool Ok;
        public string Message;
    }

    /// <summary>
    /// The sponsor market. Sponsors approach teams with offers after events (more often in the winter), with
    /// objectives fitted to what the team can realistically do. AI teams accept under the same rules the player
    /// faces. The real brands in the data are complemented by invented ones (flagged as such) so every category
    /// has a market; the invented pool is refreshed every winter.
    /// </summary>
    public static class SponsorMarket
    {
        /// <summary>Events an offer stays open.</summary>
        public const int OfferLifetimeEvents = 4;
        /// <summary>Chance per event that a team with a free slot receives an approach.</summary>
        public const double ApproachChance = 0.3;

        // ------------------------------------------------------------------ the pool

        /// <summary>Keeps enough sponsors interested in each category (invented ones are added as needed).</summary>
        public static void EnsurePool(WorldState world, GameDatabase db, DeterministicRandom rng)
        {
            foreach (var cat in db.CategoriesOrdered())
            {
                if (!cat.Simulated || cat.IsCup) continue;
                var rules = db.GetRules(cat.Id, world.Season);
                int teams = world.TeamsInCategory(cat.Id).Count;
                int target = (int)Math.Round(teams * (rules.Economy.SponsorSlots + 0.5));
                int have = 0;
                foreach (var s in SponsorService.AllTemplates(world, db))
                    if (SponsorService.CategoryWeight(s, cat) >= 0.6 && (s.CategoryPreference.Count > 0 || s.Tier >= 2)) have++;
                for (int i = have; i < target; i++)
                {
                    var s = Invent(world, db, cat, rules, rng);
                    world.Sponsors[s.Id] = s;
                }
            }
        }

        /// <summary>Winter turnover: some invented sponsors that backed nobody leave the sport, new ones arrive.</summary>
        public static void SeasonRefresh(WorldState world, GameDatabase db, DeterministicRandom rng)
        {
            var engaged = SponsorService.Engaged(world);
            var ids = new List<string>(world.Sponsors.Keys);
            ids.Sort(StringComparer.Ordinal);
            foreach (var id in ids)
                if (!engaged.Contains(id) && rng.Chance(0.25)) world.Sponsors.Remove(id);
            world.SponsorOffers.RemoveAll(o => o.StartSeason < world.Season);
            EnsurePool(world, db, rng);
        }

        private static SponsorTemplate Invent(WorldState world, GameDatabase db, ChampionshipCategory cat, CategoryRules rules, DeterministicRandom rng)
        {
            var parts = db.SponsorNames;
            var industries = new List<string>(parts.IndustryWords.Keys);
            industries.Sort(StringComparer.Ordinal);
            string industry = industries.Count > 0 ? rng.Pick(industries) : "Services";
            string name = Name(parts, industry, rng);
            double value = rules.Economy.TypicalSponsorDeal * Math.Exp(rng.Gaussian(0, 0.45));
            value = Math.Round(value / 10000) * 10000;
            double ratio = value / Math.Max(1, rules.Economy.TypicalSponsorDeal);
            var s = new SponsorTemplate
            {
                Id = world.NewId("gsp"),
                Name = name,
                Industry = industry,
                Tier = ratio > 2 ? 2 : 3,
                PaymentPerSeason = value,
                MinTeamReputation = Math.Round(MathX.Clamp(15 + (ratio - 1) * 30 + rng.Range(-8, 8), 0, 80)),
                ContractSeasons = rng.NextInt(1, 4),
                SigningBonusShare = Math.Round(rng.Range(0, 0.2), 2),
                PenaltyOnMiss = rng.Chance(0.3) ? Math.Round(rng.Range(0.1, 0.25), 2) : 0,
                IndustryExclusive = ratio > 1.5 || rng.Chance(0.5),
                Generated = true,
                DataConfidence = "fictional brand generated by the game"
            };
            s.Pyramids.Add(cat.Pyramid);
            s.CategoryPreference[cat.Id] = 1.0;
            // Some interest in the neighbouring categories of the same ladder.
            foreach (var other in db.CategoriesOrdered())
                if (other.Simulated && !other.IsCup && other.Pyramid == cat.Pyramid && Math.Abs(other.Tier - cat.Tier) == 1)
                    s.CategoryPreference[other.Id] = 0.5;
            s.Objectives.Add(new SponsorObjective { Type = SponsorObjectiveType.RaceFinishTopN, Target = 10, BonusPerOccurrence = Math.Round(value * 0.01 / 1000) * 1000 });
            s.Objectives.Add(new SponsorObjective { Type = rng.Chance(0.5) ? SponsorObjectiveType.SeasonPoints : SponsorObjectiveType.ChampionshipPositionTopN, Target = 1, SeasonBonus = Math.Round(value * 0.12 / 1000) * 1000 });
            return s;
        }

        private static string Name(SponsorNameParts parts, string industry, DeterministicRandom rng)
        {
            string root = parts.Roots.Count > 0 ? rng.Pick(parts.Roots) : "Nova";
            List<string> words;
            string word = parts.IndustryWords.TryGetValue(industry, out words) && words.Count > 0 ? rng.Pick(words) : industry;
            if (parts.Prefixes.Count > 0 && rng.Chance(0.35)) root = rng.Pick(parts.Prefixes) + root.ToLowerInvariant();
            return root + " " + word;
        }

        // ------------------------------------------------------------------ offers

        /// <summary>
        /// After each event: expired offers lapse, AI teams decide on the offers they hold, and sponsors approach
        /// teams with free slots. Offers made during the season start immediately; in the winter they start next season.
        /// </summary>
        public static void AfterEvent(WorldState world, GameDatabase db, DeterministicRandom rng, bool winter = false)
        {
            world.SponsorOffers.RemoveAll(o => o.ExpiresAfterEvent < world.EventsCompleted);
            AiDecisions(world, db);
            var engaged = SponsorService.Engaged(world);
            int season = winter ? world.Season + 1 : world.Season;
            var teams = new List<Team>(world.Teams.Values);
            teams.Sort((a, b) => string.CompareOrdinal(a.Id, b.Id));
            foreach (var team in teams)
            {
                var cat = db.GetCategory(team.CategoryId);
                if (cat == null || !cat.Simulated || cat.IsCup) continue;
                int pending = 0;
                foreach (var o in world.SponsorOffers) if (o.TeamId == team.Id) pending++;
                int free = SponsorService.Slots(db, team, season) - SponsorService.DealsIn(team, season) - pending;
                if (free <= 0 || !rng.Chance(winter ? 0.9 : ApproachChance)) continue;
                var offer = Approach(world, db, team, cat, season, engaged, rng);
                if (offer == null) continue;
                engaged.Add(offer.SponsorId);
                world.SponsorOffers.Add(offer);
                if (team.IsPlayer) world.AddNews(offer.Name + " wants to sponsor " + team.Name, "Offer: " + MathX.FormatMoney(offer.PaymentPerSeason) + " per season for " + offer.Seasons + " season(s).", team.CategoryId, true);
            }
        }

        private static SponsorOffer Approach(WorldState world, GameDatabase db, Team team, ChampionshipCategory cat, int season, HashSet<string> engaged, DeterministicRandom rng)
        {
            var candidates = new List<SponsorTemplate>();
            var weights = new Dictionary<string, double>();
            foreach (var s in SponsorService.AllTemplates(world, db))
            {
                if (engaged.Contains(s.Id)) continue;
                if (SponsorService.IndustryConflict(team, s.Industry, s.IndustryExclusive, season, season + s.ContractSeasons - 1)) continue;
                double interest = SponsorService.Interest(world, db, s, team, cat);
                if (interest <= 0.05) continue;
                candidates.Add(s);
                weights[s.Id] = interest;
            }
            if (candidates.Count == 0) return null;
            var pick = rng.PickWeighted(candidates, s => weights[s.Id]);
            return MakeOffer(world, db, team, cat, pick, season, rng, false);
        }

        public static SponsorOffer MakeOffer(WorldState world, GameDatabase db, Team team, ChampionshipCategory cat, SponsorTemplate s, int season, DeterministicRandom rng, bool renewal)
        {
            double value = SponsorService.ValueFor(s, team, cat) * rng.Range(0.9, 1.1);
            value = Math.Round(value / 1000) * 1000;
            if (value <= 0) return null;
            var offer = new SponsorOffer
            {
                Id = world.NewId("soffer"),
                SponsorId = s.Id,
                TeamId = team.Id,
                Name = s.Name,
                Industry = s.Industry,
                Tier = s.Tier,
                PaymentPerSeason = value,
                SigningBonus = Math.Round(value * s.SigningBonusShare / 1000) * 1000,
                Seasons = Math.Max(1, s.ContractSeasons),
                StartSeason = season,
                PenaltyOnMiss = s.PenaltyOnMiss,
                IndustryExclusive = s.IndustryExclusive,
                Renewal = renewal,
                ExpiresAfterEvent = world.EventsCompleted + OfferLifetimeEvents
            };
            offer.Objectives = FitObjectives(world, db, team, s, value);
            return offer;
        }

        /// <summary>A renewal proposal for a deal that is ending: terms follow the sponsor's satisfaction and the team's standing.</summary>
        public static SponsorOffer RenewalOffer(WorldState world, GameDatabase db, Team team, SponsorDeal deal, DeterministicRandom rng)
        {
            var s = SponsorService.GetTemplate(world, db, deal.SponsorId);
            var cat = db.GetCategory(team.CategoryId);
            if (s == null || cat == null) return null;
            var offer = MakeOffer(world, db, team, cat, s, world.Season + 1, rng, true);
            if (offer == null) return null;
            // The new terms follow the team's current market value; happy sponsors pay a little more and commit
            // longer, lukewarm ones less. Payments never ratchet up on their own.
            double mood = 0.85 + deal.Satisfaction / 333.0;
            offer.PaymentPerSeason = Math.Round(offer.PaymentPerSeason * mood / 1000) * 1000;
            if (deal.Satisfaction > 75) offer.Seasons = Math.Min(4, offer.Seasons + 1);
            offer.SigningBonus = 0;
            return offer;
        }

        /// <summary>
        /// Objectives a sponsor sets, fitted to the team: a top-N finish around where the team is expected to finish,
        /// points or a championship position the team can realistically reach. Bonuses scale with the deal.
        /// </summary>
        public static List<SponsorObjective> FitObjectives(WorldState world, GameDatabase db, Team team, SponsorTemplate s, double value)
        {
            var list = new List<SponsorObjective>();
            var rules = db.GetRules(team.CategoryId, world.Season);
            double riderPos = CashflowForecast.ExpectedPosition(world, team);
            int teamRank = ExpectedTeamRank(world, team);
            int rounds = Math.Max(1, Season.GameController.RoundsInSeason(world, db, team.CategoryId));
            double scale = s.PaymentPerSeason > 0 ? value / s.PaymentPerSeason : 1;
            foreach (var o in s.Objectives)
            {
                var fitted = new SponsorObjective
                {
                    Type = o.Type,
                    BonusPerOccurrence = Math.Round(o.BonusPerOccurrence * scale / 1000) * 1000,
                    SeasonBonus = Math.Round(o.SeasonBonus * scale / 1000) * 1000,
                    Target = o.Target,
                    Description = o.Description
                };
                switch (o.Type)
                {
                    case SponsorObjectiveType.RaceFinishTopN:
                        fitted.Target = Math.Max(1, Math.Round(riderPos));
                        break;
                    case SponsorObjectiveType.ChampionshipPositionTopN:
                        fitted.Target = Math.Max(o.Target, teamRank);
                        break;
                    case SponsorObjectiveType.SeasonPoints:
                        var points = rules.GetPoints("race");
                        double perRound = 0;
                        int riders = Math.Max(1, team.RiderIds.Count);
                        for (int i = 0; i < riders; i++)
                        {
                            int p = (int)Math.Round(riderPos + (i - (riders - 1) / 2.0) * 2);
                            if (p >= 1 && p <= points.Count) perRound += points[p - 1];
                        }
                        fitted.Target = Math.Max(1, Math.Round(perRound * rounds * 0.8));
                        break;
                }
                list.Add(fitted);
            }
            return list;
        }

        public static int ExpectedTeamRank(WorldState world, Team team)
        {
            double mine = TeamAI.ExpectedStrength(world, team);
            int rank = 1;
            foreach (var t in world.TeamsInCategory(team.CategoryId))
                if (t != team && TeamAI.ExpectedStrength(world, t) > mine) rank++;
            return rank;
        }

        /// <summary>AI teams take the offers they hold when the deal fits (free slot, no industry clash).</summary>
        private static void AiDecisions(WorldState world, GameDatabase db)
        {
            var offers = new List<SponsorOffer>(world.SponsorOffers);
            foreach (var o in offers)
            {
                var team = world.GetTeam(o.TeamId);
                if (team == null || team.IsPlayer) continue;
                Accept(world, db, o.Id);
            }
        }

        // ------------------------------------------------------------------ actions (player and AI alike)

        public static SponsorOffer Find(WorldState world, string offerId)
        {
            foreach (var o in world.SponsorOffers) if (o.Id == offerId) return o;
            return null;
        }

        public static List<SponsorOffer> OffersFor(WorldState world, Team team)
        {
            var list = new List<SponsorOffer>();
            foreach (var o in world.SponsorOffers) if (o.TeamId == team.Id) list.Add(o);
            return list;
        }

        public static SponsorActionResult Accept(WorldState world, GameDatabase db, string offerId)
        {
            var o = Find(world, offerId);
            var team = o != null ? world.GetTeam(o.TeamId) : null;
            if (o == null || team == null) return Fail("The offer is no longer available.");
            int last = o.StartSeason + Math.Max(1, o.Seasons) - 1;
            if (SponsorService.DealsIn(team, o.StartSeason) >= SponsorService.Slots(db, team, o.StartSeason))
                return Fail("No free sponsor slot.");
            if (SponsorService.IndustryConflict(team, o.Industry, o.IndustryExclusive, o.StartSeason, last))
                return Fail("Another sponsor of the same industry (" + o.Industry + ") has exclusivity.");
            world.SponsorOffers.Remove(o);
            SponsorService.Sign(world, team, o);
            if (team.IsPlayer) world.AddNews(o.Name + " signs with " + team.Name, MathX.FormatMoney(o.PaymentPerSeason) + " per season until " + last + ".", team.CategoryId, true);
            return new SponsorActionResult { Ok = true, Message = o.Name + " signed." };
        }

        public static SponsorActionResult Reject(WorldState world, string offerId)
        {
            var o = Find(world, offerId);
            if (o == null) return Fail("The offer is no longer available.");
            world.SponsorOffers.Remove(o);
            return new SponsorActionResult { Ok = true, Message = o.Name + " declined." };
        }

        /// <summary>
        /// Ask for better money (up to +25%). Keen sponsors may agree; each push makes the next one less likely, and a
        /// sponsor that says no may walk away. The answer is deterministic for a given offer and attempt.
        /// </summary>
        public static SponsorActionResult Counter(WorldState world, GameDatabase db, string offerId, double raise)
        {
            var o = Find(world, offerId);
            var team = o != null ? world.GetTeam(o.TeamId) : null;
            var s = o != null ? SponsorService.GetTemplate(world, db, o.SponsorId) : null;
            if (o == null || team == null || s == null) return Fail("The offer is no longer available.");
            raise = MathX.Clamp(raise, 0.01, 0.25);
            double interest = SponsorService.Interest(world, db, s, team, db.GetCategory(team.CategoryId));
            double chance = MathX.Clamp(0.25 + interest * 0.5 - raise * 1.6 - o.Counters * 0.25, 0.02, 0.9);
            var rng = new DeterministicRandom(DeterministicRandom.Combine(world.MasterSeed, DeterministicRandom.Hash(o.Id + "|" + o.Counters)));
            o.Counters++;
            if (rng.Chance(chance))
            {
                o.PaymentPerSeason = Math.Round(o.PaymentPerSeason * (1 + raise) / 1000) * 1000;
                return new SponsorActionResult { Ok = true, Message = o.Name + " agrees: " + MathX.FormatMoney(o.PaymentPerSeason) + " per season." };
            }
            if (rng.Chance(0.4 + o.Counters * 0.2))
            {
                world.SponsorOffers.Remove(o);
                return Fail(o.Name + " withdraws the offer.");
            }
            return Fail(o.Name + " keeps the original terms.");
        }

        private static SponsorActionResult Fail(string message)
        {
            return new SponsorActionResult { Ok = false, Message = message };
        }

        /// <summary>
        /// Deals that exist in the 2026 snapshot: each team's real sponsors from the data, then market deals to fill
        /// the usual number of slots (these are already signed when the game starts).
        /// </summary>
        public static void InitialDeals(WorldState world, GameDatabase db, DeterministicRandom rng)
        {
            var teams = new List<Team>(world.Teams.Values);
            teams.Sort((a, b) => string.CompareOrdinal(a.Id, b.Id));
            var engaged = SponsorService.Engaged(world);
            foreach (var team in teams)
            {
                var cat = db.GetCategory(team.CategoryId);
                if (cat == null || !cat.Simulated || cat.IsCup || team.Sponsors.Count > 0) continue;
                var home = new List<SponsorTemplate>();
                foreach (var s in db.Sponsors.Values)
                    if (s.HomeTeams.Contains(team.Id) && !engaged.Contains(s.Id)) home.Add(s);
                home.Sort((a, b) => string.CompareOrdinal(a.Id, b.Id));
                foreach (var s in home)
                {
                    engaged.Add(s.Id);
                    var o = MakeOffer(world, db, team, cat, s, world.Season, rng, false);
                    if (o == null) continue;
                    o.SigningBonus = 0;
                    o.Seasons = Math.Max(1, s.ContractSeasons) + rng.NextInt(0, 2);
                    SponsorService.Sign(world, team, o);
                }
            }
            // Fill the remaining slots, best-known teams first (they attract sponsors first).
            teams.Sort((a, b) =>
            {
                int c = b.Reputation.CompareTo(a.Reputation);
                return c != 0 ? c : string.CompareOrdinal(a.Id, b.Id);
            });
            for (int round = 0; round < 4; round++)
            {
                foreach (var team in teams)
                {
                    var cat = db.GetCategory(team.CategoryId);
                    if (cat == null || !cat.Simulated || cat.IsCup) continue;
                    if (SponsorService.DealsIn(team, world.Season) >= SponsorService.Slots(db, team, world.Season) - (round == 0 ? 1 : 0)) continue;
                    if (!rng.Chance(0.8)) continue;
                    var o = Approach(world, db, team, cat, world.Season, engaged, rng);
                    if (o == null) continue;
                    engaged.Add(o.SponsorId);
                    o.SigningBonus = 0;
                    // Deals already running: they end at different times.
                    o.StartSeason = world.Season - rng.NextInt(0, Math.Max(1, o.Seasons));
                    if (o.StartSeason + o.Seasons - 1 < world.Season) o.Seasons = world.Season - o.StartSeason + 1;
                    SponsorService.Sign(world, team, o);
                }
            }
        }
    }
